import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const component = readFileSync(new URL("../src/components/admin/FounderCommandCenter.tsx", import.meta.url), "utf8");
const migration = readFileSync(new URL("../supabase/migrations/20261115090000_founder_mobile_release_control.sql", import.meta.url), "utf8");
const app = readFileSync(new URL("../src/App.tsx", import.meta.url), "utf8");

test("Founder Menu is routed and only exposed to Super Admins", () => {
  assert.match(app, /"founder",\s*"Founder Menu"/);
  assert.match(app, /id==="founder"\?data\.profile\.role==="super_admin"/);
  assert.match(component, /role !== "super_admin"/);
});

test("release drafts do not overwrite the currently published release", () => {
  assert.match(component, /from\("mobile_app_release_drafts"\)\.upsert/);
  assert.match(component, /rpc\("publish_mobile_app_release"/);
  assert.match(migration, /create table if not exists public\.mobile_app_release_drafts/);
});

test("publishing is enforced by a database Super Admin check and monotonic versionCode", () => {
  assert.match(migration, /p\.role = 'super_admin'/);
  assert.match(migration, /p_version_code <= current_code/);
  assert.match(migration, /grant execute on function public\.publish_mobile_app_release/);
  assert.match(migration, /returns public\.mobile_app_releases\s+language plpgsql\s+security invoker/);
  assert.match(migration, /super admins delete mobile release drafts/);
});

test("release history is generated by database triggers and readable only by Super Admins", () => {
  assert.match(migration, /create table if not exists public\.mobile_app_release_history/);
  assert.match(migration, /after insert or update on public\.mobile_app_release_drafts/);
  assert.match(migration, /after insert or update on public\.mobile_app_releases/);
  assert.match(migration, /super admins read mobile release history/);
});

test("rollback preparation creates a new higher-code build instead of reusing an older APK", () => {
  assert.match(component, /Prepare rollback build/);
  assert.match(component, /Android does not allow installing an older versionCode/);
  assert.match(component, /Rebuild this code as a new APK/);
});
